// The "open-field" grammar: the chunk vocabulary for Desert and Forest maps.
//
// Where the loop grammar is corridors and rooms, this one is broad traversable
// ground with islands of blockers, so a player crossing it has several loose
// approaches instead of one route. Same 16x16 authoring rules, same derived
// edge mask — a grammar is a chunk library and a branch count, never a second
// code path.
//
// It also asks for the organic rim: a tile lattice of open ground reads as a
// grid far more readily than a lattice of rooms does, so the unused tiles
// outside the route are carved by a wobbly disc and the boundary stops being a
// 7x7 square. See `organicRim` in assemble-area.ts.
