/**
 * Turn the newest devlog screenshots into the main menu's tiles, the way PoE1
 * hangs two pictures left of its buttons.
 *
 *   node tools/devlog_to_menu.mjs
 *
 * Reads devlog/README.md (oldest section first, so the newest is at the bottom),
 * writes a WebP per tile plus a larger one for the lightbox under
 * apps/web/public/textures/ui/menu/devlog/, and the captions to
 * apps/web/src/devlog.generated.ts. `devlog.test.ts` fails when the two drift.
 * Run it whenever a capture is promoted into the devlog.
 */
import { mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const README = join(root, "devlog", "README.md");
const SHOTS = join(root, "devlog", "screenshots");
const OUT_MODULE = join(root, "apps", "web", "src", "devlog.generated.ts");
const URL_DIR = "/textures/ui/menu/devlog";
const OUT_DIR = join(root, "apps", "web", "public", ...URL_DIR.split("/").filter(Boolean));

/** One large tile and two small ones. */
export const TILE_COUNT = 3;
/** Twice the CSS size, for high-DPI screens: the large tile, the small ones, the lightbox. */
const SIZE = { large: [640, 360], small: [320, 180], full: [1280, 720] };

/** The newest `count` still screenshots, newest section first, each section in reading order. */
export function parseDevlog(text, count = TILE_COUNT) {
  const sections = [];
  let cur = null;
  for (const line of text.split(/\r?\n/)) {
    const head = /^## (\d{4}-\d{2}-\d{2})/.exec(line);
    if (head) sections.push((cur = { date: head[1], shots: [] }));
    if (!cur) continue;
    for (const m of line.matchAll(/<img src="screenshots\/([^"]+)" alt="([^"]*)"[^>]*>(?:<br>)?\s*<sub>([^<]+)<\/sub>/g)) {
      // A GIF is a clip: it does not hold still in a tile.
      if (!/\.gif$/i.test(m[1])) cur.shots.push({ file: m[1], alt: m[2], caption: m[3].trim(), date: cur.date });
    }
  }
  return sections.reverse().flatMap((s) => s.shots).slice(0, count);
}

const stem = (file) => file.replace(/\.[^.]+$/, "");

export function render(shots) {
  const rows = shots.map((s) => `  ${JSON.stringify({
    src: `${URL_DIR}/${stem(s.file)}.webp`,
    full: `${URL_DIR}/${stem(s.file)}-full.webp`,
    caption: s.caption,
    alt: s.alt,
    date: s.date,
  })},`).join("\n");
  return `// GENERATED by tools/devlog_to_menu.mjs from devlog/README.md. Do not edit.
export const DEVLOG_TILES: readonly { src: string; full: string; caption: string; alt: string; date: string }[] = [
${rows}
];
`;
}

if (process.argv[1] && process.argv[1].endsWith("devlog_to_menu.mjs")) {
  const { default: sharp } = await import("sharp");
  const shots = parseDevlog(readFileSync(README, "utf8"));
  if (shots.length < TILE_COUNT) {
    console.error(`devlog has ${shots.length} still shots, the menu needs ${TILE_COUNT}`);
    process.exit(1);
  }
  mkdirSync(OUT_DIR, { recursive: true });
  for (const f of readdirSync(OUT_DIR)) rmSync(join(OUT_DIR, f));
  for (const [i, s] of shots.entries()) {
    const src = join(SHOTS, s.file);
    const { width, height } = await sharp(src).metadata();
    // The tile is the middle of the frame: the HUD's globes, skill bar and minimap ride its edges.
    const centre = { left: Math.round(width * 0.15), top: Math.round(height * 0.1), width: Math.round(width * 0.7), height: Math.round(height * 0.7) };
    const [w, h] = i === 0 ? SIZE.large : SIZE.small;
    const name = (suffix) => join(OUT_DIR, `${stem(s.file)}${suffix}.webp`);
    await sharp(src).extract(centre).resize(w, h, { fit: "cover" }).webp({ quality: 80 }).toFile(name(""));
    await sharp(src).resize(...SIZE.full, { fit: "cover" }).webp({ quality: 80 }).toFile(name("-full"));
  }
  writeFileSync(OUT_MODULE, render(shots), "utf8");
  console.log(shots.map((s) => `${s.date} ${s.file}`).join("\n"));
}
